function printResult(index, name)

  foundlist_initialize(fl)
  local count=foundlist_getCount(fl)
  if (count==1) then
    local saddress= getAddress(fl.getAddress(index)) --get the first address
    print("m_SequenceMap[CW3MemoryUtils::ESequence::" .. name .."].address = m_StaticBaseAddresses[0] + 0x"..string.format("%x", saddress-baseAddress)..";")
  else
    print("-- No addresses found for " .. name .. " found addresses: " .. count)
    if(count == 2) then
             print(fl.getAddress(0))
             print(fl.getAddress(1))
    end
  end
  foundlist_deinitialize(fl)
end

